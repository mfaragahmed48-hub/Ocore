        // اسم وسيلة الرد للعرض
        // ==========================================

        private string GetRefundMethodDisplay(string method)
        {
            switch (method)
            {
                case "Cash":
                    return "نقدي";

                case "Card":
                    return "فيزا";

                case "InstaPay":
                    return "إنستا باي";

                default:
                    return "غير محدد";
            }
        }

